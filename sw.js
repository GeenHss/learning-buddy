/* Learning Buddy service worker: makes the app work offline.
   Bump VERSION whenever you publish a new index.html. */
const VERSION = 'v8';
const CACHE = 'learning-buddy-' + VERSION;
const SHELL = ['./', './index.html', './manifest.webmanifest',
  './icons/icon-192.png', './icons/icon-512.png', './icons/apple-touch-icon.png'];

self.addEventListener('install', e => {
  // cache:'reload' skips the browser's own HTTP cache, so we always store the newest files
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(SHELL.map(u => new Request(u, {cache:'reload'})))).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => (k.startsWith('rekenhelden-') || k.startsWith('learning-buddy-')) && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // The app page: try the internet first (to get updates), fall back to the saved copy.
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req.url, {cache:'no-store', credentials:'same-origin'})   // never use a stale copy when online
      .then(res => { const copy = res.clone(); caches.open(CACHE).then(c => c.put('./index.html', copy)); return res; })
      .catch(() => caches.match('./index.html')));
    return;
  }

  // Fonts and our own files: use the saved copy, fetch and save it the first time.
  if (url.origin === location.origin || /fonts\.(googleapis|gstatic)\.com$/.test(url.hostname)) {
    e.respondWith(caches.match(req).then(hit => hit || fetch(req).then(res => {
      const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); return res;
    })));
  }
});
